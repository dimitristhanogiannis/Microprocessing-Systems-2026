void delay_ms(uint32_t ms) {
    for(uint32_t i = 0; i < ms * 4000; i++) {	// assuming 16 MHz clock and 4 cycles per loop, we have 4000 iterations per ms
        __asm("NOP"); 							// insert no operations for delay simulation
    }
}

void uart_putc(char c) {
    while (!(USART2_SR & (1<<7)));  // pause while UART is busy sending a character (Transmit Data Register Empty = 0)
    USART2_DR = c;					// when it becomes available again, put c in Data Register
}

void uart_puts(const char *str) {   		// function to print an entire string
    while(*str) uart_putc(*str++);  		// while c != '\0' (end of string), send c to UART
}

void uart_putn(uint32_t num) { 			// function to appropriately depict numbers
    char buf[10];
    int i = 0;
    if (num == 0) { uart_putc('0'); return; }	// 0 is depicted as '0' in ASCII, no change
    while (num > 0) { buf[i++] = (num % 10) + '0'; num /= 10; } // translate all digits of a number to its correct ASCII value, using '0' as position reference
    while (i > 0) { uart_putc(buf[--i]); } 		// print them in the correct (reverse) order
}

char get_complement(char c) {		// RNA complement calculation
    if(c == 'A') return 'U';
    if(c == 'U') return 'A';
    if(c == 'G') return 'C';
    if(c == 'C') return 'G';
    return 0;
}

volatile int reset_search_flag = 0; // global search reset flag

void EXTI4_IRQHandler(void) {
    if (EXTI_PR & (1<<4)) {     // if EXTI4
        EXTI_PR |= (1<<4);      // clear pending bit

        GPIOA_ODR |= (1<<13);   // turn on PA13
        delay_ms(3000);         // for 3 seconds
        GPIOA_ODR &= ~(1<<13);  // and then turn it off

        reset_search_flag = 1;  // set flag = 1 for the app_main to see and reset
    }
}

int app_main(void) {
    RCC_AHB1ENR |= (1<<0) | (1<<3);	// enable clock for GPIOA, GPIOD
    RCC_APB1ENR |= (1<<17);			// enable clock for USART2

    GPIOA_MODER &= ~(0x0F0F00F0);
    GPIOA_MODER |= 0x050A00A0;		// set GPIOA PA12, PA13 as outputs, PA2 as TX, PA3 as RX (alternate function)
    GPIOA_AFRL  |= 0x00007700;		// set alternate function 7 for the desired functionality USART2

    GPIOD_MODER &= ~(3 << 8); 		// set GPIOD PD4 as input

    RCC_APB2ENR |= (1<<14);             // enable SYSCFG clock

    SYSCFG_EXTICR2 &= ~(0x0000000F);    // clear bits 0-3 (EXTI4)
    SYSCFG_EXTICR2 |= 0x00000003;       // set EXTI4 in Port D (0011)

    EXTI_IMR |= (1<<4);                 // enable line 4
    EXTI_RTSR |= (1<<4);                // rising edge enable

    NVIC_ISER0 |= (1<<10);              // enable EXTI4 interrupt in NVIC (position 10)

    USART2_BRR = 0x008B;				// set appropriate Baud Rate for 16 MHz clock
    USART2_CR1 = (1<<13) | (1<<3) | (1<<2);	// enable USART enable bit, Transmitter enable bit, Receiver enable bit

    char input[100];
    char comp[100];

    while(1) {
        int idx = 0;
        int reset_search = 0;

        uart_puts("Insert RNA sequence: ");

        while(1) {
        	if (reset_search_flag) { 	// look for interrupt
        		reset_search_flag = 0; 	// clear flag
        		reset_search = 1;
        		uart_puts("\r\n[!] Search Reset by PD4 !\r\n\n");
        		break;
        	}

            if (USART2_SR & (1<<5)) {	// check for new character in RX
                char c = USART2_DR;

                if (c == '\n' || c == '\r') {
                    if (idx > 0) break;	// end of sequence
                } else if (c == 'A' || c == 'U' || c == 'G' || c == 'C') {
                    input[idx++] = c;
                    uart_putc(c);			// if it is accepted, print it
                }
            }
        }

        if (reset_search) continue; 	// if there was an interrupt (PD4), do not print the accumulated characters

        input[idx] = '\0';				// finish the sequence
        uart_puts("\r\n");					// change line

        for(int i = 0; i < idx; i++) {
            comp[i] = get_complement(input[i]);	// calculate complementary sequence
        }
        comp[idx] = '\0';						// finish the sequence

        uart_puts("Complement to find: ");
        uart_puts(comp);
        uart_puts("\r\nPositions: ");

        int count = 0;
        int seq_len = sizeof(covid_seq) - 1;

        for(int i = 0; i <= seq_len - idx; i++) {	// find matches in Covid-19 sequence
            int match = 1;
            for(int j = 0; j < idx; j++) {
                if (covid_seq[i+j] != comp[j]) {
                    match = 0; break;
                }
            }
            if (match) {
                count++;
                uart_putn(i);							// keep all of the starting positions, if there are any
                uart_puts(" ");
            }
        }

        uart_puts("\r\nTotal occurrences: ");
        uart_putn(count);								// print them
        uart_puts("\r\n");

        if (count > 0) {							// if there is at least an occurrence
            GPIOA_ODR |= (1<<12);					// turn on PA12
            delay_ms(2000);							// for 2 seconds
            GPIOA_ODR &= ~(1<<12);					// and then close it
        }
    }
}
